/* ---- saturating casts (spec 17) ---- */

static inline rift_i128 rift_sat_s(rift_i128 v, rift_i128 lo, rift_i128 hi) { return v < lo ? lo : v > hi ? hi : v; }
static inline rift_u128 rift_sat_u(rift_u128 v, rift_u128 hi) { return v > hi ? hi : v; }
static inline rift_i128 rift_sat_us(rift_u128 v, rift_i128 hi) { return v > (rift_u128)hi ? hi : (rift_i128)v; }
static inline rift_u128 rift_sat_su(rift_i128 v, rift_u128 hi) { return v < 0 ? 0 : (rift_u128)v > hi ? hi : (rift_u128)v; }
static inline double rift_sat_f(double v, double lo, double hi) { return v != v ? 0 : v < lo ? lo : v > hi ? hi : v; }

/* ---- main's exit status (spec 04) ---- */

static int rift_exit_status(rift_i128 v, const rift_loc* l) {
    if (v < 0 || v > 255) {
        char msg[96];
        long long shown = (long long)v;
        snprintf(msg, sizeof msg, "main returned %lld, which is not a valid exit status (0 to 255)", shown);
        rift_panic(l, msg);
    }
    return (int)v;
}

